// Generates src/theme-light.css: the light-mode overrides for the black base theme.
// Run: node scripts/gen-light-theme.mjs
import fs from 'fs';

const esc = (c) => c.replace(/([^\w-])/g, '\\$1');

// Elements that stay dark/coloured in BOTH themes. Light-on-dark text, borders and
// translucent fills inside them keep their original (dark-theme) values.
const CTX = [
  '.keep-dark',
  '.gradient-dark-cinematic',
  '.gradient-brand-surface',
  '.gradient-accent-cta',
  '.bg-[#1769AA]',
  '.bg-[#F36B21]',
  '.bg-[#123B60]',
].map((c) => '.' + esc(c.slice(1)));
const ctx = `:is(${CTX.join(', ')})`;

const out = [];
out.push('/* AUTO-GENERATED by scripts/gen-light-theme.mjs - edit the generator, not this file. */');
out.push('/* Light mode = `html.light`. Dark (black) is the default theme. */');

// [class, property, lightValue, darkValue, kind]
// kind: '' | 'hover' | 'focus' | 'group-hover' | 'placeholder'
const rules = [];
const add = (cls, prop, light, dark, kind = '') => rules.push({ cls, prop, light, dark, kind });

// Text
add('text-white', 'color', '#17212B', '#FFFFFF');
add('text-[#EAF4FB]', 'color', '#123B60', '#EAF4FB');
for (const a of [40, 50, 60, 65, 70, 75, 80, 85, 90]) {
  add(`text-[#EAF4FB]/${a}`, 'color', `rgba(18, 59, 96, ${a / 100})`, `rgba(234, 244, 251, ${a / 100})`);
}
add('text-[#5BB4F5]', 'color', '#1769AA', '#5BB4F5');
add('text-[#5BB4F5]', 'color', '#1769AA', '#5BB4F5', 'hover');
add('text-[#5BB4F5]', 'color', '#1769AA', '#5BB4F5', 'group-hover');
add('text-[#9CA3AF]', 'color', '#64748B', '#9CA3AF');
add('text-[#9CA3AF]', 'color', '#64748B', '#9CA3AF', 'placeholder');
add('text-[#F5F5F5]', 'color', '#17212B', '#F5F5F5');

// Backgrounds
add('bg-black', 'background-color', '#F8FAFC', '#000000');
add('bg-[#0A0A0A]', 'background-color', '#FFFFFF', '#0A0A0A');
add('bg-[#141414]', 'background-color', '#EAF4FB', '#141414');
add('bg-[#050505]', 'background-color', '#F1F5F9', '#050505');
for (const a of [50, 55, 70, 80]) {
  add(`bg-[#141414]/${a}`, 'background-color', `rgba(234, 244, 251, ${a / 100})`, `rgba(20, 20, 20, ${a / 100})`);
}
add('bg-black/95', 'background-color', 'rgba(255, 255, 255, 0.95)', 'rgba(0, 0, 0, 0.95)');
add('bg-black/90', 'background-color', 'rgba(255, 255, 255, 0.9)', 'rgba(0, 0, 0, 0.9)');
add('bg-[#141414]', 'background-color', '#FFFFFF', '#141414', 'hover');
add('bg-[#141414]', 'background-color', '#FFFFFF', '#141414', 'focus');
add('bg-white/10', 'background-color', '#F1F5F9', 'rgba(255, 255, 255, 0.1)', 'hover');
add('bg-white/5', 'background-color', '#F1F5F9', 'rgba(255, 255, 255, 0.05)');
add('bg-white/10', 'background-color', '#E2E8F0', 'rgba(255, 255, 255, 0.1)');
add('bg-white/20', 'background-color', '#CBD5E1', 'rgba(255, 255, 255, 0.2)');

// Borders
add('border-white/5', 'border-color', '#F1F5F9', 'rgba(255, 255, 255, 0.05)');
add('border-white/10', 'border-color', '#E2E8F0', 'rgba(255, 255, 255, 0.1)');
add('border-white/15', 'border-color', '#CBD5E1', 'rgba(255, 255, 255, 0.15)');

const sel = (r, scope) => {
  const c = `.${r.kind === 'group-hover' ? 'group-hover:' : r.kind === 'hover' ? 'hover:' : r.kind === 'focus' ? 'focus:' : r.kind === 'placeholder' ? 'placeholder:' : ''}${r.cls}`;
  const base = esc(c.slice(1));
  const pseudo = r.kind === 'hover' ? ':hover' : r.kind === 'focus' ? ':focus' : r.kind === 'placeholder' ? '::placeholder' : '';
  const group = r.kind === 'group-hover' ? '.group:hover ' : '';
  if (scope === 'base') return `html.light ${group}.${base}${pseudo}`;
  // inside an always-dark context: descendant OR the element itself
  return [`html.light ${ctx} ${group}.${base}${pseudo}`, `html.light ${ctx}${group ? ' ' + group : ''}.${base}${pseudo}`.replace(`${ctx} .group:hover .`, `${ctx} .group:hover .`)].join(',\n');
};

for (const r of rules) {
  out.push(`${sel(r, 'base')} { ${r.prop}: ${r.light}; }`);
  out.push(`${sel(r, 'ctx')} { ${r.prop}: ${r.dark}; }`);
}

// Dividers
out.push(`html.light .divide-white\\/10 > :not(:last-child) { border-color: #E2E8F0; }`);
out.push(`html.light ${ctx} .divide-white\\/10 > :not(:last-child) { border-color: rgba(255, 255, 255, 0.1); }`);

// Gradients that were light in the original design
out.push(`html.light .from-\\[\\#141414\\] { --tw-gradient-from: #EAF4FB; }`);
out.push(`html.light .via-\\[\\#0A0A0A\\] { --tw-gradient-via: #FFFFFF; }`);
out.push(`html.light .to-\\[\\#141414\\] { --tw-gradient-to: #EAF4FB; }`);
out.push(`html.light .from-black { --tw-gradient-from: #F8FAFC; }`);
out.push(`html.light .to-black { --tw-gradient-to: #F8FAFC; }`);

// Always-dark surfaces get their brand colours back in light mode
out.push(`html.light .gradient-dark-cinematic { background: linear-gradient(160deg, #17212B 0%, #123B60 65%, #102B46 100%); }`);
out.push(`html.light .gradient-brand-surface { background: linear-gradient(135deg, #1769AA 0%, #123B60 100%); }`);
out.push(`html.light .keep-dark.bg-\\[\\#000000\\] { background-color: #17212B; }`);
out.push(`html.light .keep-dark.bg-\\[\\#0B0B0B\\] { background-color: #123B60; }`);
out.push(`html.light .keep-dark.from-\\[\\#161616\\] { --tw-gradient-from: #123B60; }`);
out.push(`html.light .keep-dark.via-\\[\\#0B0B0B\\] { --tw-gradient-via: #1769AA; }`);
out.push(`html.light .keep-dark.to-\\[\\#161616\\] { --tw-gradient-to: #123B60; }`);
out.push(`html.light .keep-dark.to-\\[\\#0B0B0B\\] { --tw-gradient-to: #1769AA; }`);

// Outlined digits (Services, How We Work, etc.)
out.push(`html.light .outlined-digit { color: transparent; background: linear-gradient(135deg, #F36B21 0%, #FF8533 45%, #D95512 100%); -webkit-background-clip: text; background-clip: text; -webkit-text-stroke: 0; filter: drop-shadow(0 2px 10px rgba(243, 107, 33, 0.3)); }`);
out.push(`html.light .group:hover .outlined-digit, html.light .outlined-digit-active { background: linear-gradient(135deg, #1769AA 0%, #123B60 60%, #F36B21 100%); -webkit-background-clip: text; background-clip: text; -webkit-text-stroke: 0; filter: drop-shadow(0 4px 14px rgba(23, 105, 170, 0.35)); transform: scale(1.04); }`);

// Page + helpers
out.push(`html.light { color: #17212B; background-color: #F8FAFC; color-scheme: light; --logo-notch: #F8FAFC; }`);
out.push(`html.light body { background-color: #F8FAFC; }`);
out.push(`html.light .keep-dark { --logo-notch: #123B60; }`);
out.push(`html.light .hover-strong:hover { color: #17212B; }`);

fs.writeFileSync(new URL('../src/theme-light.css', import.meta.url), out.join('\n') + '\n');
console.log('wrote', out.length, 'lines');
